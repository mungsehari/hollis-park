-- Uploaded images (product photos, collection photos, homepage hero)
create table media (
    id             bigint generated by default as identity primary key,
    storage_key    varchar(300) not null unique,
    url            varchar(600) not null,
    original_name  varchar(300),
    content_type   varchar(60)  not null,
    size_bytes     bigint       not null,
    alt            varchar(300),
    created_at     timestamptz  not null,
    created_by     varchar(200)
);
create index media_created_idx on media (created_at desc);

-- Several photos per product; the first one is the main photo (products.img keeps it too)
alter table products add column gallery jsonb;

-- Collections move from a static file into the database so the admin can edit them
create table collections (
    id          varchar(60) primary key,
    name        varchar(120) not null,
    tagline     varchar(300),
    intro       varchar(2000),
    image       varchar(600),
    alt         varchar(500),
    choose      jsonb,
    guide       jsonb,
    sort_order  integer not null default 0,
    active      boolean not null default true,
    updated_at  timestamptz
);

-- Editable page content, one JSON document per page ('home')
create table site_content (
    id          varchar(40) primary key,
    data        jsonb not null,
    updated_at  timestamptz
);
