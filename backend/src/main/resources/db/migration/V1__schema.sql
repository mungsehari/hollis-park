-- Hollis Park store schema (PostgreSQL)

create table products (
    id               varchar(80) primary key,
    name             varchar(120) not null,
    collection_id    varchar(60)  not null,
    line_name        varchar(120),
    colourway        varchar(120),
    swatch           varchar(300),
    price            integer      not null check (price >= 0),
    rating           double precision not null default 0,
    review_count     integer      not null default 0,
    flag             varchar(60),
    sort_rank        integer      not null default 100,
    added_on         varchar(10),
    img              varchar(500),
    context_img      varchar(500),
    context_caption  varchar(300),
    alt              varchar(500),
    blurb            varchar(1000),
    description      varchar(3000),
    care             varchar(1000),
    keywords         varchar(1000),
    colours          jsonb,
    wide             jsonb,
    specs            jsonb,
    materials        jsonb,
    fit              jsonb,
    sold_out         jsonb,
    low              jsonb,
    active           boolean      not null default true,
    updated_at       timestamptz
);
create index products_collection_idx on products (collection_id);

create table reviews (
    id            bigint generated by default as identity primary key,
    product_id    varchar(80) not null references products (id) on delete cascade,
    name          varchar(120),
    place         varchar(120),
    shoe_size     varchar(20),
    fit_score     integer not null default 0,
    rating        integer not null,
    review_date   varchar(20),
    body          varchar(2000)
);
create index reviews_product_idx on reviews (product_id);

create table orders (
    id            bigint generated by default as identity primary key,
    order_number  varchar(20) unique,
    email         varchar(200) not null,
    first_name    varchar(80)  not null,
    last_name     varchar(80)  not null,
    address       varchar(300) not null,
    city          varchar(100) not null,
    pin           varchar(10)  not null,
    ship_method   varchar(20)  not null,
    promo_code    varchar(40),
    subtotal      numeric(12, 2) not null,
    discount      numeric(12, 2) not null,
    shipping      numeric(12, 2) not null,
    tax           numeric(12, 2) not null,
    total         numeric(12, 2) not null,
    status        varchar(20)  not null,
    admin_note    varchar(2000),
    items         jsonb        not null,
    history       jsonb,
    created_at    timestamptz  not null,
    updated_at    timestamptz
);
create index orders_status_idx on orders (status);
create index orders_created_idx on orders (created_at desc);

create table contact_messages (
    id            bigint generated by default as identity primary key,
    name          varchar(120) not null,
    email         varchar(200) not null,
    topic         varchar(40)  not null,
    order_number  varchar(40),
    fitting_slot  varchar(80),
    body          varchar(4000) not null,
    status        varchar(20)  not null default 'NEW',
    created_at    timestamptz  not null
);
create index contact_status_idx on contact_messages (status, created_at desc);

create table subscribers (
    id          bigint generated by default as identity primary key,
    email       varchar(200) not null unique,
    topics      jsonb,
    created_at  timestamptz not null
);

create table staff_users (
    id             bigint generated by default as identity primary key,
    email          varchar(200) not null unique,
    name           varchar(120) not null,
    password_hash  varchar(200) not null,
    role           varchar(20)  not null check (role in ('ADMIN', 'STAFF')),
    active         boolean      not null default true,
    created_at     timestamptz  not null,
    last_login_at  timestamptz
);

create table store_settings (
    id              integer primary key check (id = 1),
    tax_mode        varchar(10)   not null check (tax_mode in ('included', 'added')),
    tax_rate        numeric(5, 4) not null check (tax_rate >= 0 and tax_rate < 1),
    tax_name        varchar(40)   not null,
    free_ship_from  integer       not null check (free_ship_from >= 0),
    ship_fee        integer       not null check (ship_fee >= 0),
    express_fee     integer       not null check (express_fee >= 0),
    updated_at      timestamptz
);

create table promo_codes (
    code        varchar(40) primary key,
    rate        numeric(5, 4) not null check (rate > 0 and rate < 1),
    active      boolean       not null default true,
    created_at  timestamptz   not null
);

-- Spring Session (admin logins survive restarts and work across several API instances)
create table spring_session (
    primary_id            char(36) not null,
    session_id            char(36) not null,
    creation_time         bigint   not null,
    last_access_time      bigint   not null,
    max_inactive_interval int      not null,
    expiry_time           bigint   not null,
    principal_name        varchar(100),
    constraint spring_session_pk primary key (primary_id)
);
create unique index spring_session_ix1 on spring_session (session_id);
create index spring_session_ix2 on spring_session (expiry_time);
create index spring_session_ix3 on spring_session (principal_name);

create table spring_session_attributes (
    session_primary_id char(36)     not null,
    attribute_name     varchar(200) not null,
    attribute_bytes    bytea        not null,
    constraint spring_session_attributes_pk primary key (session_primary_id, attribute_name),
    constraint spring_session_attributes_fk foreign key (session_primary_id) references spring_session (primary_id) on delete cascade
);
